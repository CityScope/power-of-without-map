/**
 * Structured questionnaire metadata aligned with the SSRN-style informality KPI stack
 * (Architecture + Populace composite; Site as a third pillar profile).
 * Drives wizard UI — do not duplicate field lists in form components.
 */

export type QuestionSection = "architecture" | "populace" | "site";
export type QuestionSource = "SSRN taxonomy" | "SW taxonomy" | "derived";

export type QuestionOption = { label: string; value: string | number };

export type QuestionInputType =
  | "number"
  | "percentage"
  | "select"
  | "multiselect"
  | "boolean"
  | "slider"
  | "textarea";

export type QuestionnaireQuestion = {
  id: string;
  /** Wizard step index (1 = location UI only; 2 = basic meta; 3–7 = schema blocks; 8 = review). */
  wizardStep: number;
  section: QuestionSection;
  subsection: string;
  label: string;
  helpText: string;
  /** Deeper methodological wording for experts or tooltips. */
  expertHelp?: string;
  inputType: QuestionInputType;
  options?: QuestionOption[];
  unit?: string;
  /** Key stored in survey answers / passed to `SurveyAnswers` for the calculator. */
  mapsToVariable: string;
  /** Human-readable link to the composite formula layer. */
  mapsToFormula: string;
  requiredForCoreScore: boolean;
  canBeEstimatedFromOpenData: boolean;
  source: QuestionSource;
};

